select set_config('contest.test_forfeit',public.contest_create_game('Smoke Forfeit','CIRCLE',now(),now()+interval '1 hour',50,'Rollback-only test')->>'id',true);
select set_config('contest.test_future',public.contest_create_game('Smoke Future','CIRCLE',now()+interval '1 hour',now()+interval '2 hours',100,'Rollback-only test')->>'id',true);

-- A game cannot start without an opponent. A client cannot overwrite server-owned points.
