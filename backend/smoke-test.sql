-- A third player cannot join, submit, forfeit, modify a profile, or write a game directly.
select set_config('request.jwt.claims',jsonb_build_object('sub',id,'role','authenticated')::text,true)
from contest_test_users where label='outsider';
select public.contest_ensure_profile();
do $$ declare blocked boolean; changed integer; begin
  blocked:=false;
  begin perform public.contest_join_game(current_setting('contest.test_game')::uuid); exception when others then blocked:=true; end;
  assert blocked, 'third player joined';
  blocked:=false;
  begin perform public.contest_save_result(current_setting('contest.test_game')::uuid,array[5,4,3,2,1]); exception when others then blocked:=true; end;
  assert blocked, 'outsider submitted result';
  blocked:=false;
  begin perform public.contest_forfeit_game(current_setting('contest.test_game')::uuid); exception when others then blocked:=true; end;
  assert blocked, 'outsider forfeited another game';
  update public.contest_profiles set name='Wrong user' where id=(select id from contest_test_users where label='host');
  get diagnostics changed = row_count;
  assert changed=0, 'RLS permitted editing another profile';
  blocked:=false;
  begin update public.contest_games set winner_id=auth.uid() where id=current_setting('contest.test_game')::uuid; exception when insufficient_privilege then blocked:=true; end;
  assert blocked, 'direct game modification permitted';
  assert (select count(*) from public.contest_participants)=0, 'outsider read private participation';
end $$;

reset role;
update public.contest_games set image_seed=42 where id=current_setting('contest.test_solved_image')::uuid;
set local role authenticated;
select set_config('request.jwt.claims',jsonb_build_object('sub',id,'role','authenticated')::text,true)
from contest_test_users where label='host';
select public.contest_start_game(current_setting('contest.test_game')::uuid);
select public.contest_start_game(current_setting('contest.test_image')::uuid);
do $$ declare blocked boolean; g jsonb; after_points integer; begin
  blocked:=false;
  begin perform public.contest_save_result(current_setting('contest.test_game')::uuid,array[5,4,null,2,1]); exception when others then blocked:=true; end;
  assert blocked, 'null circle move accepted';
  blocked:=false;
  begin perform public.contest_save_result(current_setting('contest.test_game')::uuid,array[1,2,3,4,5]); exception when others then blocked:=true; end;
  assert blocked, 'ascending circles accepted';
  blocked:=false;
  begin perform public.contest_save_result(current_setting('contest.test_image')::uuid,array[-1]); exception when others then blocked:=true; end;
  assert blocked, 'invalid image move accepted';
  g:=public.contest_save_result(current_setting('contest.test_game')::uuid,array[5,4,3,2,1]);
  assert g->>'status'='FINISHED' and (g->>'winner_id')::uuid=auth.uid(), 'valid Circle winner not recorded';
  g:=public.contest_save_result(current_setting('contest.test_game')::uuid,array[5,4,3,2,1]);
  select points into after_points from public.contest_profiles where id=auth.uid();
  assert after_points=100, 'repeat result awarded twice';
  assert (public.contest_statistics()->>'circle_wins')::integer=1, 'statistics missing victory';
  assert (public.contest_statistics()->>'weekly_points')::integer=100, 'weekly points incorrect';
  perform public.contest_start_game(current_setting('contest.test_solved_image')::uuid);
  -- A* solution for seed 42; independent from the scramble generator.
  g:=public.contest_save_result(current_setting('contest.test_solved_image')::uuid,array[1,4,3,6,7,8,5,2,1,4,3,6,7,4,5,8,7,4,3,0,1,2,5,8]);
  assert g->>'status'='FINISHED' and (g->>'winner_id')::uuid=auth.uid(),'valid Image replay was not accepted';
  assert (public.contest_statistics()->>'image_wins')::integer=1,'Image win missing from statistics';
end $$;

